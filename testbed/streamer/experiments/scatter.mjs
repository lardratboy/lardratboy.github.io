/* The scatter world, measured (docs/scatter-plan.md, phase 6).

     node experiments/scatter.mjs           # ~2 min; writes docs/scatter-results.md and docs/data/scatter.json
     node experiments/scatter.mjs --quick   # D = 10 only, prints (~5 s)

   It measures job times, so run it on an idle machine.

   For D = 10, 11 and 12 (64, 256 and 1,024 specimens on `hills`), on one
   thread, buildScatter's phases: the ground (fromField), pass A (build
   and fingerprint each recipe), pass B (turn, rest, cut, intern), the
   graft, and the voxel counts. Then the world: nodes, how many the ground
   holds, nodes and snapshot bytes per specimen, blocks, recipes skipped
   as repeats, voxels. And the specimens themselves: how full, how many
   blocks each was cut into, how far each rests above the ground's lowest
   point under it (the downhill overhang).

   What the views cost (raster against ray, the stencil) is in
   experiments/rays.mjs, which flies the scatter world with the others. */
import { writeFileSync, mkdirSync } from 'node:fs';
import { createCounts } from '../dag-core.js';
import { buildScatter, scatterDesc, groundOf, TABLE_WORDS } from '../scatter-core.js';

const QUICK = process.argv.includes('--quick');
const started = performance.now();
const med = a => { const s = [...a].sort((x, y) => x - y); return s[s.length >> 1]; };
const pct = (a, p) => { const s = [...a].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(p * s.length))]; };
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(r => `| ${r.join(' | ')} |`)].join('\n');
const n = v => v.toLocaleString('en');

const out = { quick: QUICK, worlds: [] };
for (const D of QUICK ? [10] : [10, 11, 12]){
  const desc = scatterDesc({ D }), b = buildScatter(desc);
  const t0 = performance.now(), counts = createCounts(b.store), countsMs = performance.now() - t0;
  const N = b.layout.cells.length, R = desc.R, top = groundOf(desc).top;
  // Per specimen: voxels, and the overhang: the gap under its box between
  // where it rests and the lowest ground below its footprint.
  const fill = [], overhang = [];
  for (let c = 0; c < N; c++){
    const [, , x0, y0, z0, count] = b.table.subarray(TABLE_WORDS * c, TABLE_WORDS * (c + 1));
    fill.push(count / R ** 3);
    let low = Infinity;
    for (let z = 0; z < R; z += 4) for (let x = 0; x < R; x += 4) low = Math.min(low, top(x0 + x, z0 + z));
    overhang.push(y0 - 1 - low);
  }
  const spec = b.nodes - b.ms.groundNodes;
  out.worlds.push({ D, specimens: N, nodes: b.nodes, groundNodes: b.ms.groundNodes, specimenNodes: spec, perSpecimen: spec / N,
    snapshotBytes: b.nodes * 44, blocks: b.blocks, blocksPerSpecimen: b.blocks / N, skipped: b.skipped, recipes: b.prints.length,
    voxels: counts.of(b.root), fillMedian: med(fill), overhangMedian: med(overhang), overhangP90: pct(overhang, 0.9), overhangMax: Math.max(...overhang),
    ms: { ground: b.ms.ground, passA: b.ms.build, passB: b.ms.place, graft: b.ms.graft, counts: countsMs } });
  console.log(`D=${D}: ${N} specimens, ${n(b.nodes)} nodes, ${((performance.now() - started) / 1000).toFixed(0)} s`);
}
const seconds = (performance.now() - started) / 1000;
const W = out.worlds;
const text = [
  '# The scatter world: results',
  '',
  `Generated by \`node experiments/scatter.mjs${QUICK ? ' --quick' : ''}\` on ${new Date().toISOString().slice(0, 10)} in ${seconds.toFixed(0)} s, one thread, Node ${process.versions.node}. ` +
  'The reading is in [scatter-findings.md](scatter-findings.md), the method in [scatter-plan.md](scatter-plan.md). What the views cost is in [ray-results.md](ray-results.md) (the scatter world is one of its worlds).',
  '',
  '## 1. The build, one thread',
  '',
  '*pass A* builds and fingerprints each recipe (repeats included); *pass B* turns, rests, cuts and interns each placed specimen. The page runs both across workers (scatter-build.js), and the ground on a worker of its own.',
  '',
  table(['D', 'specimens', 'ground ms', 'pass A ms', 'pass B ms', 'graft ms', 'counts ms', 'total s'],
    W.map(w => [w.D, n(w.specimens), w.ms.ground.toFixed(0), w.ms.passA.toFixed(0), w.ms.passB.toFixed(0), w.ms.graft.toFixed(0), w.ms.counts.toFixed(0),
      ((w.ms.ground + w.ms.passA + w.ms.passB + w.ms.graft + w.ms.counts) / 1000).toFixed(1)])),
  '',
  '## 2. The world',
  '',
  '*snapshot* is 44 bytes a node (9 key words and a Float64 count; no poses), which every chunk worker receives a copy of. *skipped* recipes were repeats of earlier ones, up to rotation and mirror.',
  '',
  table(['D', 'nodes', 'ground nodes', 'nodes per specimen', 'snapshot MB', 'snapshot KB per specimen', 'blocks (per specimen)', 'recipes / skipped', 'voxels'],
    W.map(w => [w.D, n(w.nodes), n(w.groundNodes), w.perSpecimen.toFixed(0), (w.snapshotBytes / 1048576).toFixed(1), (w.perSpecimen * 44 / 1024).toFixed(1),
      `${n(w.blocks)} (${w.blocksPerSpecimen.toFixed(1)})`, `${n(w.recipes)} / ${w.skipped}`, n(w.voxels)])),
  '',
  '## 3. The specimens',
  '',
  '*full* is voxels over 64³. *overhang* is how far a specimen\'s lowest voxel row sits above the lowest ground under its footprint (sampled every 4 voxels): what resting on contact leaves open on the downhill side.',
  '',
  table(['D', 'full (median)', 'overhang median', 'p90', 'max'],
    W.map(w => [w.D, (100 * w.fillMedian).toFixed(1) + '%', w.overhangMedian, w.overhangP90, w.overhangMax])),
  '',
].join('\n');

if (QUICK) console.log(text);
else {
  mkdirSync(new URL('../docs/data/', import.meta.url), { recursive: true });
  writeFileSync(new URL('../docs/scatter-results.md', import.meta.url), text);
  writeFileSync(new URL('../docs/data/scatter.json', import.meta.url), JSON.stringify(out, null, 1));
  console.log(`wrote docs/scatter-results.md and docs/data/scatter.json (${seconds.toFixed(0)} s)`);
}
