/* ================== BIMOMIRROR CORE ==================================
   Generator #9 (`?g=mirror`, design in bimomirror.md): one bimoblock,
   seven images. A bimoblock folds voxels around the specimen centre; a
   bimomirror folds whole bimoblocks. The outer tier cuts the specimen into
   r × r × r cells, and every cell holds the same child, a bimoblock built
   on the inner tiers, turned by the arrangement group G.

     Every outer cell gets the child on the inner tiers, turned by the
     group element that brings its orbit representative there, and folded
     by the group generated by its own fold and the cell's stabiliser.

   At radix 2 no cell centre lies on a mirror plane or an axis, and each
   G below acts regularly on the eight octants: one child, seven images,
   no ambiguity. The child can be fully asymmetric and the whole is still
   exactly G-symmetric. At radix 3 the middle slabs sit on the planes, so
   a child there is folded by its cell's stabiliser too and the children
   grow more symmetric towards the centre (the kaleidoscope). An even
   radix above 2 puts translated copies of the child in each octant.

     group   copy (a control: eight translated, unturned children),
             mirror (D2h), turn (D4, chiral), pinwheel (C4h), twist (D2d);
             the four are every order-8 subgroup of Oh that is regular on
             the octants, up to turning the cube
     seat    which of the 8 sign changes flips the child before it is
             placed: which corner of it faces the specimen centre. A child
             symmetric along that diagonal lifts the whole (mirror × C3 is
             Th, turn × C3 is O)

   The whole's symmetry group is predicted from the recipe alone: m is in
   it when, at every cell c, g(m·c)⁻¹ · m · g(c), seated, is in the
   child's fold (48 × r³ group products, no voxel scan).

   Then the shared instanceArrays(). No orbit labels: specimens are
   coloured by position in every mode. Pure like the other cores: no DOM,
   no THREE, runs in the worker.
   ================================================================ */
import { Core, createBimoblockCore } from './bimoblock-core.js';

const { GROUPS, applyG, mulE } = Core;

/* The cube group as tables: products, inverses, determinant, element
   order, and each element as a signed permutation for the scatter loop
   (applyG(v, e)[j] = SG[3e + j] · v[PM[3e + j]]). */
const MUL = new Uint8Array(48 * 48), INV = new Uint8Array(48), PM = new Uint8Array(144), SG = new Int8Array(144);
const DET = new Int8Array(48), ORDER = new Uint8Array(48);
for (let a = 0; a < 48; a++){
  for (let b = 0; b < 48; b++){ MUL[a * 48 + b] = mulE(a, b); if (MUL[a * 48 + b] === 0) INV[a] = b; }
  const w = applyG([1, 2, 3], a);
  for (let j = 0; j < 3; j++){ PM[3 * a + j] = Math.abs(w[j]) - 1; SG[3 * a + j] = Math.sign(w[j]); }
  const x = applyG([1, 0, 0], a), y = applyG([0, 1, 0], a), z = applyG([0, 0, 1], a);
  DET[a] = x[0] * (y[1] * z[2] - y[2] * z[1]) - x[1] * (y[0] * z[2] - y[2] * z[0]) + x[2] * (y[0] * z[1] - y[1] * z[0]);
}
for (let a = 0; a < 48; a++){ let p = a, n = 1; while (p !== 0){ p = MUL[p * 48 + a]; n++; } ORDER[a] = n; }

/* The element that does to (x, y, z) what f does. */
const code = f => {
  const t = f([1, 2, 3]);
  for (let e = 0; e < 48; e++){ const w = applyG([1, 2, 3], e); if (w[0] === t[0] && w[1] === t[1] && w[2] === t[2]) return e; }
  throw new Error('not a cube symmetry');
};
/** The subgroup of Oh the elements generate, as sorted element codes.
 *  @param {number[]} gens @returns {number[]} */
export function closure(gens){
  const set = new Set([0]), queue = [0];
  while (queue.length){
    const a = queue.pop();
    for (const g of gens){ const c = MUL[a * 48 + g]; if (!set.has(c)){ set.add(c); queue.push(c); } }
  }
  return [...set].sort((a, b) => a - b);
}

const MX = code(v => [-v[0], v[1], v[2]]), MY = code(v => [v[0], -v[1], v[2]]), MZ = code(v => [v[0], v[1], -v[2]]);
const R90Y = code(v => [v[2], v[1], -v[0]]), R180X = code(v => [v[0], -v[1], -v[2]]);
const S4Y = MUL[R90Y * 48 + MY];
export const INVERSION = code(v => [-v[0], -v[1], -v[2]]);

/* The arrangements, only ever appended. The three with a special axis use
   y, so they read as up / down like the bimoblock C4 pinwheel. */
export const ARRANGEMENTS = [
  { name:'copy',     gens:[],               note:'eight translated copies, none turned' },
  { name:'mirror',   gens:[MX, MY, MZ],     note:'every gap is a mirror plane' },
  { name:'turn',     gens:[R90Y, R180X],    note:'turns only, no mirror: a left hand stays left' },
  { name:'pinwheel', gens:[R90Y, MY],       note:'a quarter-turn pinwheel each layer, the floor a mirror' },
  { name:'twist',    gens:[MX, S4Y],        note:'side neighbours mirrored, the layer below turned over' }
].map(a => ({ ...a, els: closure(a.gens) }));
export const ARRANGEMENT_NAMES = ARRANGEMENTS.map(a => a.name);

/* Seat k flips the child by sign change k (bit 0 x, bit 1 y, bit 2 z),
   which is Oh element k. Named by the child's corner that then faces the
   specimen centre from the seed octant (+++): seat 0 leaves the child's
   −−− corner there. */
export const SEAT_NAMES = Array.from({ length: 8 }, (_, k) => [0, 1, 2].map(a => k >> a & 1 ? '+' : '−').join(''));

/* The stabiliser of the octant diagonal (1, 1, 1) in Oh: C3v. A child
   symmetry gains the whole something only when it lies in here. */
const C3V = new Uint8Array(48);
for (let e = 0; e < 48; e++){ const w = applyG([1, 1, 1], e); C3V[e] = w[0] === 1 && w[1] === 1 && w[2] === 1 ? 1 : 0; }
const conj = (s, k) => MUL[MUL[s * 48 + k] * 48 + s];   // s·k·s, a sign change being its own inverse
/* For each bimoblock fold, the seats that line up the most of it with the
   diagonal: C3 and S6 two, C4v four, the rest all eight (nothing to line
   up, or everything lined up already). Always 2, 4 or 8. */
export const ALIGNED_SEATS = GROUPS.map(g => {
  const score = Array.from({ length: 8 }, (_, s) => g.els.filter(k => C3V[conj(s, k)]).length);
  const best = Math.max(...score);
  return score.flatMap((v, s) => v === best ? [s] : []);
});

/* Schoenflies and Hermann–Mauguin names of a subgroup of Oh, from its
   order and a few element counts. Every subgroup class is told apart
   except by which axes it uses, which the arrangement already says. */
const HM = { Oh:'m3̄m', O:'432', Th:'m3̄', Td:'4̄3m', T:'23', D4h:'4/mmm', D3d:'3̄m', D4:'422', C4h:'4/m', D2h:'mmm',
  C4v:'4mm', D2d:'4̄2m', D3:'32', S6:'3̄', C3v:'3m', C4:'4', S4:'4̄', D2:'222', C2h:'2/m', C2v:'mm2', C3:'3', Ci:'1̄', C2:'2', Cs:'m', C1:'1' };
export const WHOLE_NOTES = { Oh:'full octahedral', O:'chiral octahedral: every turn of the cube, no mirror',
  Th:'pyritohedral: no 4-fold axis', Td:'tetrahedral', T:'chiral tetrahedral' };
/** @param {number[]} els @returns {{name:string, hm:string, order:number}} */
export function groupName(els){
  const n = els.length, inv = els.includes(INVERSION), chiral = els.every(e => DET[e] > 0);
  const c4 = els.some(e => DET[e] > 0 && ORDER[e] === 4), s4 = els.some(e => DET[e] < 0 && ORDER[e] === 4);
  const name = n === 48 ? 'Oh' : n === 24 ? (chiral ? 'O' : inv ? 'Th' : 'Td') : n === 16 ? 'D4h'
    : n === 12 ? (chiral ? 'T' : 'D3d')
    : n === 8 ? (chiral ? 'D4' : inv ? (c4 ? 'C4h' : 'D2h') : (c4 ? 'C4v' : 'D2d'))
    : n === 6 ? (chiral ? 'D3' : inv ? 'S6' : 'C3v')
    : n === 4 ? (c4 ? 'C4' : s4 ? 'S4' : chiral ? 'D2' : inv ? 'C2h' : 'C2v')
    : n === 3 ? 'C3' : n === 2 ? (inv ? 'Ci' : chiral ? 'C2' : 'Cs') : 'C1';
  return { name, hm: HM[name], order: n };
}

/** @param {ReturnType<typeof createBimoblockCore>} [bimo] reuse an existing bimoblock core */
export function createMirrorCore(bimo = createBimoblockCore()){
  const { levelResolution } = bimo;

  /* The outer cells as orbits of G, in doubled centred coordinates (so
     radix 2's ±½ are ±1). Each orbit's representative is its member
     furthest towards +++ (the seed octant), and each cell is placed by
     the lowest element that brings the representative there. A child's
     fold is its own fold and the representative's stabiliser, seated:
     the child is flipped by s before it is placed, so a stabiliser
     element k must be a symmetry of the unflipped child as s·k·s. */
  function mirrorLayout(group, seat, sym, r0){
    const G = (ARRANGEMENTS[group] ?? ARRANGEMENTS[1]).els, F = GROUPS[sym].els, s = seat & 7;
    const h = r0 - 1, n = r0 * r0 * r0;
    const at = i => [2 * (i % r0) - h, 2 * (Math.floor(i / r0) % r0) - h, 2 * Math.floor(i / (r0 * r0)) - h];
    const idx = v => (v[0] + h) / 2 + r0 * (v[1] + h) / 2 + r0 * r0 * (v[2] + h) / 2;
    const orbit = new Int16Array(n).fill(-1), place = new Uint8Array(n), orbits = [];
    for (let i = 0; i < n; i++){
      if (orbit[i] >= 0) continue;
      const c0 = at(i);
      let rep = c0;
      for (const e of G){
        const w = applyG(c0, e), d = (w[0] + w[1] + w[2]) - (rep[0] + rep[1] + rep[2]);
        if (d > 0 || (d === 0 && (w[0] > rep[0] || (w[0] === rep[0] && (w[1] > rep[1] || (w[1] === rep[1] && w[2] > rep[2])))))) rep = w;
      }
      const o = orbits.length, stab = [];
      let size = 0;
      for (const e of G){
        const k = idx(applyG(rep, e));
        if (k === idx(rep)) stab.push(e);
        if (orbit[k] < 0){ orbit[k] = o; place[k] = e; size++; }
      }
      const fold = stab.length > 1 ? closure([...F, ...stab.map(k => conj(s, k))]) : F;
      orbits.push({ rep: idx(rep), size, fold });
    }
    return { r0, group, seat: s, sym, orbit, place, orbits, at, idx };
  }

  /* The whole's symmetry group, predicted: m is in it when every cell's
     child lands on its image cell's child, turned by an element of that
     child's fold. Children with the same fold are the same child. */
  function wholeGroup(L){
    const { r0, orbit, place, orbits, seat: s, at, idx } = L, n = r0 * r0 * r0;
    const keys = orbits.map(o => o.fold.join(','));
    const inF = orbits.map(o => { const a = new Uint8Array(48); for (const e of o.fold) a[e] = 1; return a; });
    const cells = Array.from({ length: n }, (_, c) => at(c));
    const out = [];
    for (let m = 0; m < 48; m++){
      let ok = true;
      for (let c = 0; c < n && ok; c++){
        const mc = idx(applyG(cells[c], m)), O = orbit[c];
        if (keys[orbit[mc]] !== keys[O]){ ok = false; break; }
        const k = MUL[MUL[INV[place[mc]] * 48 + m] * 48 + place[c]];
        if (!inF[O][conj(s, k)]) ok = false;
      }
      if (ok) out.push(m);
    }
    return out;
  }

  /** @param {import('../types.js').MirrorRecipe} M @param {import('../types.js').Level[]} levels
   *  @returns {Omit<import('../types.js').OccResult, 'orbit' | 'orbitOrder'> & {meta:Object}} */
  function mirrorOcc(M, levels){
    const started = performance.now();
    const R = levelResolution(levels), r0 = levels[0].radix, group = M.group | 0, seat = M.seat & 7;
    const base = { sym:M.sym, arch:M.arch, field:M.field, lift:M.lift, density:M.density, seed:M.seed };
    const F = GROUPS[M.sym].els;
    // One tier has nothing inside to mirror: the plain bimoblock.
    if (levels.length < 2){
      const b = bimo.bimoblockOcc(base, levels), whole = groupName(F);
      return { occ: b.occ, R, filled: b.filled, envelopeCells: b.envelopeCells,
        meta: { fallback: true, whole: whole.name, hm: whole.hm, wholeOrder: whole.order, aligned: false,
          childR: R, cells: 1, kinds: [[whole.name, 1]] },
        timings: { evaluate: performance.now() - started, select: 0 } };
    }
    const inner = levels.slice(1), Rc = R / r0, hc = Rc - 1;
    const L = mirrorLayout(group, seat, M.sym, r0);
    /* One build per distinct fold, with its occupied voxels as doubled
       centred coordinates for the scatter. */
    const builds = new Map();
    const childOf = o => {
      const key = o.fold.join(',');
      if (!builds.has(key)){
        const b = bimo.bimoblockOcc(o.fold.length === F.length ? base : { ...base, foldEls: o.fold }, inner);
        const V = new Int16Array(3 * b.filled);
        let v = 0;
        for (let z = 0; z < Rc; z++) for (let y = 0; y < Rc; y++) for (let x = 0; x < Rc; x++)
          if (b.occ[x + Rc * y + Rc * Rc * z]){ V[v++] = 2 * x - hc; V[v++] = 2 * y - hc; V[v++] = 2 * z - hc; }
        builds.set(key, { V, filled: b.filled, envelopeCells: b.envelopeCells, fold: groupName(o.fold).name });
      }
      return builds.get(key);
    };
    const occ = new Uint8Array(R * R * R), kinds = new Map();
    let filled = 0, envelopeCells = 0;
    for (let c = 0; c < r0 * r0 * r0; c++){
      const child = childOf(L.orbits[L.orbit[c]]);
      kinds.set(child.fold, (kinds.get(child.fold) || 0) + 1);
      // A child voxel λ lands at g·s·λ in the cell's own frame.
      const u = MUL[L.place[c] * 48 + seat], a = 3 * u, V = child.V;
      const ox = (c % r0) * Rc, oy = (Math.floor(c / r0) % r0) * Rc, oz = Math.floor(c / (r0 * r0)) * Rc;
      for (let k = 0; k < V.length; k += 3){
        const x = (SG[a] * V[k + PM[a]] + hc) / 2, y = (SG[a + 1] * V[k + PM[a + 1]] + hc) / 2, z = (SG[a + 2] * V[k + PM[a + 2]] + hc) / 2;
        occ[(ox + x) + R * (oy + y) + R * R * (oz + z)] = 1;
      }
      filled += child.filled; envelopeCells += child.envelopeCells;
    }
    const whole = groupName(wholeGroup(L)), aligned = ALIGNED_SEATS[M.sym].length < 8 && ALIGNED_SEATS[M.sym].includes(seat);
    return { occ, R, filled, envelopeCells,
      meta: { fallback: false, whole: whole.name, hm: whole.hm, wholeOrder: whole.order, aligned,
        childR: Rc, cells: r0 * r0 * r0, kinds: [...kinds] },
      timings: { evaluate: performance.now() - started, select: 0 } };
  }

  /** @param {import('../types.js').MirrorRecipe} M @param {import('../types.js').Level[]} levels
   *  @returns {import('../types.js').BuildResult} */
  function buildMirror(M, levels){
    const started = performance.now();
    const src = mirrorOcc(M, levels);
    const instances = bimo.instanceArrays(src.occ, 0, src.filled, levels, src.R);
    return { occ: src.occ, R: src.R, filled: src.filled, envelopeCells: src.envelopeCells, instances,
      meta: src.meta,
      timings: { evaluate: src.timings.evaluate, select: 0,
        mesh: instances.timings.mesh, bounds: instances.timings.bounds,
        total: performance.now() - started } };
  }

  /* For tests: the cell layout and the predicted group on their own. */
  return { buildMirror, mirrorOcc, mirrorLayout, wholeGroup };
}
